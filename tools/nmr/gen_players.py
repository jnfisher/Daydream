#!/usr/bin/env python3
"""Writes crates/daydream-nmr/src/players.rs: the player tables NMR edits but never exports.

NMR's `.mdb` has no Users, Bank Books or Gangs tables; its User, Bank and Gang editors read
the records directly. Daydream gives them NmrTable shapes so the same row editors, imports
and deletes work on them. They are not in `columns::TABLES`, so the `.mdb` export is
unchanged. Labels follow NMR's editors where it has one.

    python3 tools/nmr/gen_players.py > crates/daydream-nmr/src/players.rs
"""

# (member, byte length) -> VB type, as NMR's types hold them
VB = {1: "Byte", 2: "Integer", 4: "Long"}


def num(name, member, size, at=0, unsigned=False):
    if unsigned:
        return (name, "Double", f"Source::Unsigned(&[p({member!r}, {at}, {size})])")
    return (name, "Long", f"Source::Element {{ vb: Vb::{VB[size]}, pieces: &[p({member!r}, {at}, {size})] }}")


def text(name, member, size):
    return (name, f"Text({size})", f"Source::Element {{ vb: Vb::Text, pieces: &[p({member!r}, 0, {size})] }}")


def family(label, members, count):
    """`count` slots of parallel arrays, `members` = [(suffix, member, size), ...]."""
    out = []
    for i in range(count):
        for suffix, member, size in members:
            out.append(num(f"{label} {i}{suffix}", member, size, at=i * size))
    return out


USERS = [
    text("BBS Name", "userid", 30),
    text("First Name", "firstname", 11),
    text("Last Name", "lastname", 19),
    text("Title", "title", 20),
    num("Race", "race", 2),
    num("Class", "class", 2),
    num("Level", "level", 2),
    num("Exp Billions", "expbil", 4, unsigned=True),
    num("Exp", "exprem", 4, unsigned=True),
    num("Lives", "lives", 2),
    num("CP", "cp", 2),
    num("Total CP", "totalcp", 2),
    num("Map Number", "map", 4),
    num("Room Number", "room", 4),
]
for label, base, cur in [
    ("INT", "basint", "intel"),
    ("WIL", "baswil", "wil"),
    ("STR", "basstr", "str"),
    ("HEA", "bashea", "hea"),
    ("AGL", "basagi", "agi"),
    ("CHM", "bascha", "cha"),
]:
    USERS += [num(f"Base {label}", base, 2), num(label, cur, 2)]
USERS += [
    num("Max HP", "maxhp", 2),
    num("HP", "hp", 2),
    num("Max Mana", "maxmana", 2),
    num("Mana", "mana", 2),
    num("Max Weight", "maxwgt", 2),
    num("Weight", "wgt", 2),
    num("Max Energy", "maxenergy", 2),
    num("Energy", "energy", 2),
    num("Max MR", "maxmr", 2),
    num("MR", "mr", 2),
    num("Poison", "poison", 2),
    num("HP Bonus", "hpbonus", 4),
    num("Mana Bonus", "manabonus", 4),
    num("Perception", "perception", 2),
    num("Stealth", "stealth", 2),
    num("Martial Arts", "martial", 2),
    num("Thievery", "thievery", 2),
    num("Spellcasting", "spellcast", 2),
    num("Traps", "traps", 2),
    num("Disarm", "disarm", 2),
    num("Picklocks", "picklocks", 2),
    num("Tracking", "tracking", 2),
    num("Runic", "runic", 4),
    num("Platinum", "platinum", 4),
    num("Gold", "gold", 4),
    num("Silver", "silver", 4),
    num("Copper", "copper", 4),
    num("Weapon", "weapon", 4),
    num("Evil Points", "evil", 2),
    num("Broadcast Channel", "bchannel", 2),
    text("Gang", "gang", 20),
    text("Suicide Password", "suicpw", 9),
]
USERS += family("Item", [("", "items", 4), (" Uses", "itemuses", 2)], 100)
USERS += family("Key", [("", "keys", 4), (" Uses", "keyuses", 2)], 50)
USERS += family("Spellbook", [("", "spellbook", 2)], 100)
USERS += family("Worn", [("", "worn", 4), (" Uses", "wornuses", 2)], 20)
USERS += family("Spell Cast", [("", "spells", 2), (" Value", "spellvals", 2), (" Rounds", "spellrnds", 2)], 10)
USERS += family("Trail", [(" Map", "trailmaps", 4), (" Room", "trailrooms", 4)], 20)
USERS += family("Ability", [("", "abils", 2), (" Value", "abilvals", 2)], 30)

BANKS = [
    text("BBS Name", "userid", 30),
    num("Shop #", "bank", 4),
    num("Amount", "balance", 4),
    num("Loan", "loan", 4),
]

GANGS = [
    text("KeyName", "key", 20),
    text("Display Name", "name", 20),
    num("Base Exp", "exp", 4, unsigned=True),
    text("Leader", "leader", 30),
    num("Date Created", "created", 2),
    num("Members", "members", 2),
    num("Roll Over Exp", "overexp", 4, unsigned=True),
    num("Times Rolled", "overflows", 2),
]

TABLES = [
    ("Users", "Users", ("idxUsers", ["BBS Name"]), USERS),
    ("BankBooks", "BankBooks", ("idxBankBooks", ["BBS Name", "Shop #"]), BANKS),
    ("Gangs", "Gangs", ("idxGangs", ["KeyName"]), GANGS),
]

print("// @generated by tools/nmr/gen_players.py; do not edit.")
print()
print("//! The player tables NMR's User, Bank and Gang editors edit. NMR's `.mdb` has no such")
print("//! tables, so these are Daydream's own shapes in NMR's terms; they are not in")
print("//! [`crate::columns::TABLES`] and the `.mdb` export does not write them.")
print()
print("use daydream_wcc::tables::Table;")
print()
print("use crate::schema::{Column, ColumnType, Index, NmrTable, Source, Vb, p};")
print()
print("/// Users, Bank Books and Gangs.")
print("pub static TABLES: &[NmrTable] = &[")
for name, kind, (idx, cols), columns in TABLES:
    print("    NmrTable {")
    print(f'        name: "{name}",')
    print(f"        table: Some(Table::{kind}),")
    key = ", ".join(f'"{c}"' for c in cols)
    print(f'        index: Some(Index {{ name: "{idx}", columns: &[{key}], primary: true }}),')
    print("        columns: &[")
    for cname, ty, source in columns:
        source = source.replace("'", '"')
        print(f'            Column {{ name: "{cname}", ty: ColumnType::{ty}, optional: false, source: {source} }},')
    print("        ],")
    print("    },")
print("];")
