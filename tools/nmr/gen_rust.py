"""Write joined.json (gen.py's output) as Rust: crates/daydream-nmr/src/columns.rs."""
import json
import sys

FILE_TABLE = {
    "Rooms": "Rooms", "Classes": "Classes", "Races": "Races", "Spells": "Spells",
    "Monsters": "Monsters", "Items": "Items", "Shops": "Shops", "Messages": "Messages",
    "Textblocks": "TextBlocks", "Actions": "Actions",
}
TYPE = {"adInteger": "Long", "adDouble": "Double", "adVarWChar": "Text", "adLongVarWChar": "Memo"}
VB = {"Long": "Long", "Integer": "Integer", "Byte": "Byte", "String": "Text"}


def rs(s):
    return json.dumps(s)


def column(c):
    t = TYPE[c["type"]]
    ty = f"ColumnType::Text({c['size']})" if t == "Text" else f"ColumnType::{t}"
    s = c["source"]
    if s is None:
        src = "Source::Info"
    elif "expr" in s:
        src = {"0": "Source::Zero", "decrypted": "Source::TextblockData"}[s["expr"]]
    else:
        pieces = ", ".join(f"p({rs(m)}, {at}, {n})" for m, at, n in s["pieces"])
        if s["wrap"] == "SLong2ULong":
            assert s["vb"] == "Long"
            src = f"Source::Unsigned(&[{pieces}])"
        else:
            assert s["wrap"] is None, s
            src = f"Source::Element {{ vb: Vb::{VB[s['vb']]}, pieces: &[{pieces}] }}"
        src += f" /* {s['nmr']} */"
    opt = "true" if c.get("optional") else "false"
    return f"        Column {{ name: {rs(c['name'])}, ty: {ty}, optional: {opt}, source: {src} }},"


def main():
    d = json.load(open(sys.argv[1]))
    out = [
        "// @generated by tools/nmr/gen_rust.py from Nightmare Redux's own source; do not edit.",
        "// See tools/nmr/README.md to regenerate.",
        "",
        "use daydream_wcc::tables::Table;",
        "",
        "use crate::schema::{Column, ColumnType, Index, NmrTable, Source, Vb, p};",
        "",
        "/// Every table of NMR's `.mdb`, in the order `CreateAccessTables` creates them.",
        "pub static TABLES: &[NmrTable] = &[",
    ]
    for t in d["tables"]:
        name = t["table"]
        idx = [i for i in d["indexes"] if i["table"] == name]
        if idx:
            i = idx[0]
            cols = ", ".join(rs(c) for c in i["columns"])
            index = f"Some(Index {{ name: {rs(i['name'])}, columns: &[{cols}], primary: {str(i['primary']).lower()} }})"
        else:
            index = "None"
        ft = f"Some(Table::{FILE_TABLE[name]})" if name in FILE_TABLE else "None"
        out.append("    NmrTable {")
        out.append(f"        name: {rs(name)},")
        out.append(f"        table: {ft},")
        out.append(f"        index: {index},")
        out.append("        columns: &[")
        out.extend("    " + column(c) for c in t["columns"])
        out.append("        ],")
        out.append("    },")
    out.append("];")
    print("\n".join(out))


main()
